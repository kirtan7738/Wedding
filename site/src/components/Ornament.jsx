import seal from '../assets/ornaments/seal.svg?raw';
import toran from '../assets/ornaments/toran.svg?raw';
import toranBottom from '../assets/ornaments/toran-bottom.svg?raw';
import toranShort from '../assets/ornaments/toran-short.svg?raw';
import garlandSide from '../assets/ornaments/garland-side.svg?raw';
import arch from '../assets/ornaments/arch.svg?raw';
import divider from '../assets/ornaments/divider.svg?raw';
import union from '../assets/ornaments/union.svg?raw';
import thali from '../assets/ornaments/thali.svg?raw';
import diyas from '../assets/ornaments/diyas.svg?raw';
import mandala from '../assets/ornaments/mandala.svg?raw';
import edgeArches from '../assets/ornaments/edge-arches.svg?raw';

const SVGS = {
  seal,
  toran,
  'toran-bottom': toranBottom,
  'toran-short': toranShort,
  'garland-side': garlandSide,
  arch,
  divider,
  union,
  thali,
  diyas,
  mandala,
  'edge-arches': edgeArches,
};

export const ORNAMENT_NAMES = Object.keys(SVGS);

/** Decorative inline SVG (generated by scripts/ornaments.mjs). Colours come from CSS classes. */
export default function Ornament({ name, className = '', ...rest }) {
  const markup = SVGS[name];
  if (!markup) throw new Error(`Unknown ornament "${name}"`);
  return <span className={`ornament ornament--${name} ${className}`} dangerouslySetInnerHTML={{ __html: markup }} {...rest} />;
}
